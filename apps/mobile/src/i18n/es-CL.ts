const plural = (n: number, one: string, many: string) => `${n} ${n === 1 ? one : many}`;

/** Número con coma decimal, como se escribe en Chile. */
export function formatDecimal(value: number, digits = 1): string {
  return value.toFixed(digits).replace('.', ',');
}

/** Minutos a «1 h 15 min», «45 min». */
export function formatDuration(minutes: number): string {
  const h = Math.floor(minutes / 60);
  const m = minutes % 60;
  if (!h) return `${m} min`;
  return m ? `${h} h ${m} min` : `${h} h`;
}

/** Categorías de la nómina RCE (Reglamento de Clasificación de Especies, Chile). */
const RCE_CATEGORIES: Record<string, string> = {
  EX: 'Extinta', EW: 'Extinta en estado silvestre', CR: 'En peligro crítico', EN: 'En peligro', VU: 'Vulnerable',
  NT: 'Casi amenazada', LC: 'Preocupación menor', DD: 'Datos insuficientes',
};

/** Categoría RCE con su nombre, p. ej. «Vulnerable (VU)»; un código desconocido se muestra tal cual. */
export function rceCategory(code: string): string {
  return RCE_CATEGORIES[code] ? `${RCE_CATEGORIES[code]} (${code})` : code;
}

