/** Primera letra en minúscula, para encadenar un rasgo de la ficha dentro de una frase de Wilo. */
function lower(text: string): string {
  return text.charAt(0).toLowerCase() + text.slice(1);
}

/** Fecha ISO (AAAA-MM-DD) a formato es-CL sin depender de la zona horaria. */
export function formatDate(iso: string): string {
  const [year, month, day] = iso.split('-');
  return `${day}-${month}-${year}`;
}

const MONTHS = ['ene', 'feb', 'mar', 'abr', 'may', 'jun', 'jul', 'ago', 'sept', 'oct', 'nov', 'dic'];

/** Fecha ISO (AAAA-MM-DD) corta, p. ej. «28 oct 2026». */
export function formatShortDate(iso: string): string {
  const [year, month, day] = iso.split('-');
  return `${Number(day)} ${MONTHS[Number(month) - 1]} ${year}`;
}

/** Fecha ISO (AAAA-MM-DD) partida para un sello: día y mes corto, p. ej. «29» y «oct». */
export function formatStampDate(iso: string): { day: string; month: string } {
  const [, month, day] = iso.split('-');
  return { day: String(Number(day)), month: MONTHS[Number(month) - 1] };
}
